@app.delete("/v1/sessions/{session_id}")
async def delete_session_endpoint(session_id: str):
    """Delete a session's server-side conversation mapping.

    Design change: sessions have NO automatic TTL/expiry anymore -- they
    live indefinitely until explicitly deleted here. This call is
    broadcast to every connected worker (both backends); whichever one
    (if any) actually holds `session_id` removes it from its local
    SessionStore (memory + disk).

    After a successful delete, any subsequent request using this
    `session_id` (via the X-Session-ID header) is treated as a brand-new
    conversation -- the worker-side fallback that already exists for an
    unknown/expired session_id (mode="continue" silently downgrades to
    mode="new", surfaced via `x_meta.mode_fallback`) kicks in automatically.

    Idempotent: deleting a session_id that doesn't exist (or was already
    deleted) is not an error -- it simply reports `"deleted": false`.

    Returns:
        {"session_id": "...", "deleted": true|false, "workers_checked": N}
    """
    result = await worker_mgr.delete_session(session_id)
    return JSONResponse(content=result)


@app.post("/v1/chat/completions")
async def chat_completions(request: Request, req: ChatCompletionRequest):
    """Unified chat completions — routes to DeepSeek or Qwen by `model`.

    Session continuity is driven by the X-Session-ID header (standard for both
    backends). The legacy body field `mode` is ignored.
    """
    start_time = time.time()

    try:
        backend, model_account = resolve_backend_and_account(req.model)
        # An account named in the `model` field (e.g. "deepseek(account1)")
        # takes priority over the legacy `preferred_account` body field.
        preferred_account = model_account or req.preferred_account

        # ── Session: X-Session-ID header is the standard (body session_id is
        #    accepted as a fallback for old clients). mode is derived purely
        #    from whether a session id is present; body "mode" is ignored. ──
        session_id = (
            request.headers.get("X-Session-ID", "").strip()
            or (req.session_id or "").strip()
            or None
        )
        mode = "continue" if session_id else "new"
        if not session_id:
            session_id = f"sess-{uuid.uuid4().hex[:16]}"

        # ── Common payload pieces (both backends) ──
        attachments = None
        if req.attachments:
            attachments = [
                {"filename": a.filename, "data": a.data, "mime_type": a.mime_type}
                for a in req.attachments
            ]
        tools_payload = [t.model_dump() for t in req.tools] if req.tools else None
        messages_payload = [m.model_dump(exclude_none=True) for m in req.messages]

        # Kept for x_meta (DeepSeek only)
        model_tab = deep_think = web_search = None

        if backend == "deepseek":
            # think_mode alias → (model_tab, deep_think, web_search)
            think_mode_params = _resolve_think_mode(req)
            model_tab = req.model_tab or think_mode_params.get("model_tab")
            deep_think = (
                req.deep_think if req.deep_think is not None
                else think_mode_params.get("deep_think", False)
            )
            web_search = (
                req.web_search if req.web_search is not None
                else think_mode_params.get("web_search", False)
            )
            model_tab = model_tab or "instant"

            system_prompt = "\n\n".join(
                m.content for m in req.messages
                if m.role == "system" and isinstance(m.content, str) and m.content.strip()
            ) or None
            tool_messages = [
                {
                    "role":         m.role,
                    "tool_call_id": m.tool_call_id,
                    "name":         m.name,
                    "content":      m.content if isinstance(m.content, str)
                                    else json.dumps(m.content, ensure_ascii=False),
                }
                for m in req.messages if m.role == "tool"
            ] or None

            task_fields = {
                "prompt": req.last_user_message(),
                "mode": mode,
                "session_id": session_id,
                "preferred_account": preferred_account,
                "model_tab": model_tab,
                "deep_think": deep_think,
                "web_search": web_search,
                "attachments": attachments,
                "tools": tools_payload,
                "max_tokens": req.max_tokens,
                "system_prompt": system_prompt,
                "tool_messages": tool_messages,
                "messages": messages_payload,
            }
        elif backend == "grok":
            # v1: chat-only, no think_mode/model_tab/deep_think/web_search.
            # Uses the deepseek-style envelope/result shape (ok/text/account/
            # conversation_url) — same shape the retired ChatGPT worker used,
            # REUSED unchanged for Grok (see GROK_BACKEND.md).
            task_fields = {
                "prompt": req.last_user_message(),
                "mode": mode,
                "session_id": session_id,
                "preferred_account": preferred_account,
                "attachments": attachments,
                "messages": messages_payload,
                "max_tokens": req.max_tokens,
            }
        else:  # backend == "qwen"
            # think_mode passed through as-is; the Qwen worker derives its own
            # prompt/mode from messages + its session store.
            task_fields = {
                "messages": messages_payload,
                "model": req.model,
                "stream": req.stream,
                "think_mode": req.think_mode,
                "session_id": session_id,
                "max_tokens": req.max_tokens,
                "task_type": req.task_type or "chat",
                "tools": tools_payload,
                "tool_choice": req.tool_choice if req.tools else None,
                "attachments": attachments or [],
                "preferred_cookie": preferred_account,
            }

        # ── Dispatch to a worker of the resolved backend ──
        result = await worker_mgr.dispatch(
            backend=backend,
            task_fields=task_fields,
            mode=mode,
            session_id=session_id,
            preferred_account=preferred_account,
        )

        # ── Normalise the two worker result shapes into one ──
        if backend == "qwen":
            if not result.get("success"):
                raise HTTPException(
                    status_code=502,
                    detail=result.get("error", "Qwen worker error"),
                )
            response_text = result.get("response", "")
            worker_usage = result.get("usage") or {}
            tool_calls = (
                result.get("tool_calls")
                if result.get("finish_reason") == "tool_calls" else None
            )
            account_id = result.get("cookie_file")
            conversation_url = result.get("conversation_url")
            actual_mode = mode
            mode_fallback = False
        else:  # deepseek | grok (same result shape: ok/text/account/conversation_url)
            if not result.get("ok"):
                raise HTTPException(
                    status_code=500,
                    detail=result.get("error", f"{backend} worker error"),
                )
            response_text = result.get("text", "")
            worker_usage = result.get("usage") or {}
            tool_calls = result.get("tool_calls")
            account_id = result.get("account")
            conversation_url = result.get("conversation_url")
            actual_mode = result.get("mode", mode)
            mode_fallback = result.get("mode_fallback", False)

        # Token usage (prefer worker's accurate count, fall back to estimate).
        prompt_tokens = worker_usage.get("prompt_tokens")
        completion_tokens = worker_usage.get("completion_tokens")
        if prompt_tokens is None:
            prompt_tokens = _token_estimate(req.last_user_message())
        if completion_tokens is None:
            completion_tokens = _token_estimate(response_text)
        total_tokens = worker_usage.get(
            "total_tokens", prompt_tokens + completion_tokens
        )

        finish_reason = "tool_calls" if tool_calls else "stop"
        choice = {
            "index": 0,
            "message": {
                "role": "assistant",
                # OpenAI spec: content must be null when returning tool_calls.
                "content": None if tool_calls else response_text,
            },
            "finish_reason": finish_reason,
        }
        if tool_calls:
            choice["message"]["tool_calls"] = tool_calls

        x_meta = {
            "session_id": session_id,
            "backend": backend,               # ← model routing surfaced to client
            "mode": actual_mode,
            "mode_fallback": mode_fallback,
            "account": account_id,
            "conversation_url": conversation_url,
            "response_time": time.time() - start_time,
            "timestamp": time.time(),
        }
        if backend == "deepseek":
            x_meta["model_tab"] = model_tab
            x_meta["deep_think"] = deep_think
            x_meta["web_search"] = web_search

        # Fold worker-supplied x_metadata without clobbering VPS-set keys.
        for _k, _v in (result.get("x_metadata") or {}).items():
            x_meta.setdefault(_k, _v)

        response_data = {
            "id": _make_id(),
            "object": "chat.completion",
            "created": int(time.time()),
            "model": req.model,
            "choices": [choice],
            "usage": {
                "prompt_tokens": prompt_tokens,
                "completion_tokens": completion_tokens,
                "total_tokens": total_tokens,
            },
            "x_meta": x_meta,
        }

        headers = {
            "X-Session-ID": session_id,
            "X-Backend": backend,
        }
        if account_id:
            headers["X-Account-Name"] = str(account_id)
        if conversation_url:
            headers["X-Conversation-URL"] = str(conversation_url)

        return JSONResponse(content=response_data, headers=headers)

    except HTTPException:
        raise
    except TimeoutError as e:
        raise HTTPException(status_code=504, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


