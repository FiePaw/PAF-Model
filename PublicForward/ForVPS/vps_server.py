class ChatMessage(BaseModel):
    role: str
    content: Any = None  # str, list of content parts, or None (for tool_calls)
    name: Optional[str] = None
    # Tool calling support (parity with PAF-ModelQwen):
    tool_calls: Optional[list] = None    # set when role=assistant & has tool_call
    tool_call_id: Optional[str] = None   # set when role=tool (tool result)


class ToolFunctionDef(BaseModel):
    name: str
    description: Optional[str] = None
    parameters: Optional[dict] = None


class Tool(BaseModel):
    type: str = "function"
    function: ToolFunctionDef


class AttachmentPayload(BaseModel):
    """Feature 9: Enhanced attachment with filename + data + mime_type."""

    filename: str
    data: str  # base64-encoded
    mime_type: str


class ChatCompletionRequest(BaseModel):
    model: str = "deepseek-chat"
    messages: list[ChatMessage]
    stream: bool = False
    temperature: Optional[float] = None
    max_tokens: Optional[int] = None
    tools: Optional[list[Tool]] = None
    # Custom DeepSeek extensions:
    deep_think: Optional[bool] = None
    web_search: Optional[bool] = None
    model_tab: Optional[str] = None
    session_id: Optional[str] = None
    mode: Optional[str] = None  # "new" | "continue"
    attachments: Optional[list[AttachmentPayload]] = None
    # think_mode: DeepSeek alias (resolved to model_tab/deep_think/web_search)
    # OR Qwen think mode ("auto"|"thinking"|"fast") — passed through as-is.
    think_mode: Optional[str] = None
    # Feature 4: preferred_account routing (DeepSeek account name / Qwen cookie file)
    preferred_account: Optional[str] = None
    # Qwen-specific: task_type ("chat" | "create_image" | "create_video" | "web_search")
    task_type: Optional[str] = None
    # Tool choice (Qwen forwards this; DeepSeek ignores it)
    tool_choice: Optional[str] = "auto"

    def last_user_message(self) -> str:
        for msg in reversed(self.messages):
            if msg.role == "user":
                if isinstance(msg.content, str):
                    return msg.content
                if isinstance(msg.content, list):
                    parts = [
                        p.get("text", "")
                        for p in msg.content
                        if isinstance(p, dict) and p.get("type") == "text"
                    ]
                    return "\n".join(parts)
        return ""


