class WorkerEntry:
    def __init__(
        self, worker_id: str, ws: WebSocket, max_concurrent: int,
        accounts: list, backend: str = "deepseek"
    ) -> None:
        self.worker_id = worker_id
        self.ws = ws
        self.max_concurrent = max_concurrent
        self.accounts = accounts
        self.backend = backend        # ← "deepseek" | "qwen" (model routing)
        self.in_flight = 0
        self.connected_at = time.time()
        self.last_ping = time.time()


class WorkerManager:
    def __init__(self) -> None:
        self.workers: dict[str, WorkerEntry] = {}
        self._futures: dict[str, asyncio.Future] = {}
        self._session_worker: dict[str, str] = {}
        self._rr_index = 0
        self._lock = asyncio.Lock()
        self._worker_counter = 0

    # ----- Feature 2: VPS-generated worker IDs ------------------------ #
    def _generate_worker_id(self, hostname: str) -> str:
        """Generate unique worker ID on VPS side."""
        self._worker_counter += 1
        return f"worker-{hostname}-{self._worker_counter:03d}"

    # ----- registration ---------------------------------------------- #
    async def register(
        self, ws: WebSocket, hostname: str, max_concurrent: int,
        accounts: list, backend: str = "deepseek"
    ) -> str:
        worker_id = self._generate_worker_id(hostname)
        async with self._lock:
            self.workers[worker_id] = WorkerEntry(
                worker_id, ws, max_concurrent, accounts, backend
            )
        print(f"[vps] worker registered: {worker_id} backend={backend} accounts={accounts}")
        return worker_id

    async def unregister(self, worker_id: str) -> None:
        async with self._lock:
            self.workers.pop(worker_id, None)
            # Clean up session affinity
            to_remove = [k for k, v in self._session_worker.items() if v == worker_id]
            for k in to_remove:
                self._session_worker.pop(k, None)
        print(f"[vps] worker unregistered: {worker_id}")

    # ----- Feature 4: update_accounts runtime ------------------------ #
    async def update_accounts(self, worker_id: str, accounts: list[str]) -> None:
        """Update account list for a worker at runtime."""
        async with self._lock:
            if worker_id in self.workers:
                self.workers[worker_id].accounts = accounts
                print(f"[vps] updated accounts for {worker_id}: {accounts}")

    @staticmethod
    def _account_matches(account: Any, name: str) -> bool:
        """Match a preferred-account name against a worker account entry.

        DeepSeek accounts are plain strings; Qwen accounts are dicts
        ({"account"|"cookie_file"|"name": ...}). Handle both.
        """
        if isinstance(account, str):
            return account == name
        if isinstance(account, dict):
            return name in (
                account.get("account"),
                account.get("cookie_file"),
                account.get("name"),
            )
        return False

    # ----- Feature 3: Worker wait timeout (backend-aware) ------------ #
    async def dispatch(
        self,
        backend: str,
        task_fields: dict,
        mode: str = "new",
        session_id: Optional[str] = None,
        preferred_account: Optional[str] = None,
    ) -> dict:
        """Dispatch a task to a worker of the given *backend*."""
        # Session affinity for continue mode — the browser lives on one worker.
        if mode == "continue" and session_id and session_id in self._session_worker:
            worker_id = self._session_worker[session_id]
            if worker_id in self.workers and self.workers[worker_id].backend == backend:
                return await self._dispatch_to_worker(
                    worker_id, backend, task_fields, session_id
                )

        # Wait for an available worker (of this backend) with timeout.
        start_wait = time.time()
        while time.time() - start_wait < WORKER_WAIT_TIMEOUT:
            worker_id = await self._pick_worker(backend, preferred_account)
            if worker_id:
                if session_id:
                    self._session_worker[session_id] = worker_id
                return await self._dispatch_to_worker(
                    worker_id, backend, task_fields, session_id
                )
            await asyncio.sleep(0.5)

        raise TimeoutError(f"No available '{backend}' worker within timeout")

    async def _pick_worker(
        self, backend: str, preferred_account: Optional[str] = None
    ) -> Optional[str]:
        """Pick least-loaded worker of *backend*, optionally filtering by account."""
        async with self._lock:
            candidates = [
                w
                for w in self.workers.values()
                if w.backend == backend
                and w.in_flight < w.max_concurrent
                and (
                    not preferred_account
                    or any(self._account_matches(a, preferred_account) for a in w.accounts)
                )
            ]
            if not candidates:
                return None
            # Round-robin among candidates
            self._rr_index = (self._rr_index + 1) % len(candidates)
            return candidates[self._rr_index].worker_id

    async def _dispatch_to_worker(
        self,
        worker_id: str,
        backend: str,
        task_fields: dict,
        session_id: Optional[str],
    ) -> dict:
        worker = self.workers.get(worker_id)
        if not worker:
            raise RuntimeError(f"Worker {worker_id} not found")

        task_id = f"task-{uuid.uuid4().hex[:12]}"
        future: asyncio.Future = asyncio.Future()
        self._futures[task_id] = future

        worker.in_flight += 1

        try:
            if backend == "qwen":
                # Qwen worker protocol: {"type":"task","request_id","payload"}
                envelope = {
                    "type": "task",
                    "request_id": task_id,
                    "payload": task_fields,
                }
            else:
                # DeepSeek worker protocol: {"type":"task","task_id","request"}
                envelope = {
                    "type": "task",
                    "task_id": task_id,
                    "request": task_fields,
                }
            await worker.ws.send_json(envelope)
            result = await asyncio.wait_for(future, timeout=REQUEST_TIMEOUT)
            return result
        finally:
            worker.in_flight -= 1
            self._futures.pop(task_id, None)

    # ----- result handling (both worker protocols) ------------------- #
    async def handle_result(self, msg: dict) -> None:
        # DeepSeek worker: {"type":"result","task_id","result":{...}}
        # Qwen worker:     {"type":"result","request_id","data":{...}}
        task_id = msg.get("task_id") or msg.get("request_id")
        payload = msg.get("result")
        if payload is None:
            payload = msg.get("data", {})
        if task_id in self._futures:
            self._futures[task_id].set_result(payload or {})

    # ----- Feature 13: reject_future on error ------------------------ #
    async def handle_error(self, msg: dict) -> None:
        """Immediately reject future when worker sends error (both protocols)."""
        task_id = msg.get("task_id") or msg.get("request_id")
        if task_id in self._futures:
            # DeepSeek uses "error"; Qwen uses "message".
            error_msg = msg.get("error") or msg.get("message") or "Worker error"
            status = msg.get("status", 500)
            # Create HTTPException to propagate status
            exc = HTTPException(status_code=status, detail=error_msg)
            self._futures[task_id].set_exception(exc)

    # ----- Feature 12: Worker stats ---------------------------------- #
    def get_stats(self) -> dict:
        """Get detailed worker statistics."""
        return {
            "total_workers": len(self.workers),
            "workers": [
                {
                    "worker_id": w.worker_id,
                    "backend": w.backend,
                    "accounts": w.accounts,
                    "max_concurrent": w.max_concurrent,
                    "in_flight": w.in_flight,
                    "connected_at": w.connected_at,
                    "uptime_seconds": time.time() - w.connected_at,
                }
                for w in self.workers.values()
            ],
            "total_accounts": sum(len(w.accounts) for w in self.workers.values()),
            "busy_slots": sum(w.in_flight for w in self.workers.values()),
        }

    @staticmethod
    def _account_id(account: Any) -> str:
        """Normalise an account entry (str or dict) to a display id."""
        if isinstance(account, str):
            return account
        if isinstance(account, dict):
            return str(
                account.get("account")
                or account.get("cookie_file")
                or account.get("name")
                or account
            )
        return str(account)

    # ----- Feature 5: List all available accounts (with backend) ----- #
    def list_all_accounts(self) -> list[dict]:
        """List all accounts across all workers, tagged with their backend."""
        seen: set[tuple[str, str]] = set()
        out: list[dict] = []
        for w in self.workers.values():
            for a in w.accounts:
                aid = self._account_id(a)
                key = (aid, w.backend)
                if key in seen:
                    continue
                seen.add(key)
                out.append({"id": aid, "backend": w.backend})
        out.sort(key=lambda d: (d["backend"], d["id"]))
        return out


